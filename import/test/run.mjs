import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { parseCardPage, extractThumb, parseLeaderSkill } from '../parse-card.mjs';
const html = readFileSync(new URL('./fixture.html', import.meta.url), 'utf8');
const r = parseCardPage(html, 'Super Saiyan Counterstrike Super Saiyan Goku');
assert.ok(r.ok, r.reason);
const c = r.card;
assert.equal(c.id, '12485'); assert.equal(c.rarity, 'UR'); assert.equal(c.type, 'TEQ'); assert.equal(c.class, 'Super');
assert.equal(c.name, 'Super Saiyan Goku'); assert.equal(c.title, 'Super Saiyan Counterstrike');
assert.deepEqual(c.links, ['Golden Warrior','Saiyan Warrior Race','Super Saiyan','Z Fighters','Prepared for Battle','Fierce Battle']);
assert.equal(c.categories.length, 5);
assert.equal(c.stats.atk.released, 14765); assert.equal(c.stats.hp.locked, 11356);
assert.equal(c.global, true); assert.equal(c.leader[0].pct, 170); assert.deepEqual(c.leader[0].cats, ['Powerful Comeback']);
assert.ok(extractThumb(html).includes('Card_1024850'));
const ls = parseLeaderSkill('"GT Heroes" Category Ki +3 and HP, ATK & DEF +170%;\nor\n"Goku\'s Family" Category Ki +3 and HP, ATK & DEF +150%');
assert.equal(ls.length, 2); assert.equal(ls[1].pct, 150);
const ls2 = parseLeaderSkill('"Fusion" Category Ki +3, HP & ATK +170% and DEF +130%; or PHY Type Ki +3 and HP, ATK & DEF +90%');
assert.equal(ls2[0].pct, 170); assert.equal(ls2[1].types[0].type, 'PHY'); assert.equal(ls2[1].pct, 90);
const ls3 = parseLeaderSkill('Super Class Ki +3 and HP, ATK & DEF +80%');
assert.deepEqual(ls3[0].classes, ['Super']); assert.equal(ls3[0].types.length, 0);
console.log('Parseur OK', JSON.stringify(c).slice(0, 200));
